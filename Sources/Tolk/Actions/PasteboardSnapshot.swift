import AppKit

/// Full copy of a pasteboard: every item with every type's data, in order.
/// Used to put the user's clipboard back after the synthetic ⌘C / ⌘V.
struct PasteboardSnapshot: Equatable {
    struct Item: Equatable { var entries: [(type: NSPasteboard.PasteboardType, data: Data)]
        static func == (a: Item, b: Item) -> Bool {
            a.entries.map(\.type) == b.entries.map(\.type) && a.entries.map(\.data) == b.entries.map(\.data)
        }
    }
    var items: [Item]

    var isEmpty: Bool { items.isEmpty }

    static func capture(_ pb: NSPasteboard = .general) -> PasteboardSnapshot {
        let items = (pb.pasteboardItems ?? []).map { item in
            Item(entries: item.types.compactMap { t in item.data(forType: t).map { (t, $0) } })
        }
        return PasteboardSnapshot(items: items.filter { !$0.entries.isEmpty })
    }

    /// Writes the snapshot back. Returns the pasteboard's new `changeCount`.
    @discardableResult func restore(to pb: NSPasteboard = .general) -> Int {
        pb.clearContents()
        let objects: [NSPasteboardItem] = items.map { item in
            let p = NSPasteboardItem()
            for e in item.entries { p.setData(e.data, forType: e.type) }
            return p
        }
        if !objects.isEmpty { pb.writeObjects(objects) }
        return pb.changeCount
    }
}

extension NSPasteboard.PasteboardType {
    /// nspasteboard.org convention: clipboard managers skip such entries (our temporary translation).
    static let tolkTransient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let tolkAutoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
}
