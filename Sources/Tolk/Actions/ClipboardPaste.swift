import AppKit

/// Replaces what is selected in the frontmost app with `text` through the clipboard: clipboard = text (marked
/// transient, so clipboard managers skip it), synthetic ⌘V, then the clipboard goes back to what it was
/// (unless something else wrote to it meanwhile). ⌘Z in the app undoes the paste.
/// Shared by the quick actions and «Перевод при наборе».
enum ClipboardPaste {
    @MainActor
    static func paste(_ text: String) async {
        let pb = NSPasteboard.general
        let before = PasteboardSnapshot.capture(pb)
        pb.clearContents()
        pb.setString(text, forType: .string)
        pb.setData(Data(), forType: .tolkTransient)
        pb.setData(Data(), forType: .tolkAutoGenerated)
        let ours = pb.changeCount
        KeySynth.paste()
        await sleepIgnoringCancel(0.5)
        if pb.changeCount == ours { before.restore(to: pb) }
    }
}
